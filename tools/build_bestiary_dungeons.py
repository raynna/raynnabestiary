"""Export licensed NorgannonDB dungeon relationships, retaining upstream credits.
Run after cloning tools/data-cache/NorgannonDB; no third-party runtime is shipped.
"""
from pathlib import Path
import json,subprocess
from lupa.lua51 import LuaRuntime
root=Path(__file__).resolve().parents[1];src=root/'tools/data-cache/NorgannonDB'
lua=LuaRuntime();lua.execute((src/'core/api.lua').read_text())
for name in ['world','npcs']:lua.execute((src/f'data/{name}.lua').read_text())
db=lua.globals().NorgannonDB
revision=subprocess.check_output(['git','-C',str(src),'rev-parse','HEAD'],text=True).strip()
def encode(v):
 if isinstance(v,dict):return '{'+','.join('['+encode(k)+']='+encode(x) for k,x in v.items())+'}'
 if isinstance(v,list):return '{'+','.join(map(encode,v))+'}'
 if v is None:return 'nil'
 return json.dumps(v,ensure_ascii=False)
records={};pairs=0
for key,instance in db.instances.items():
 if not instance.credits:continue
 bosses={}
 for _,boss in instance.bosses.items():
  if not boss.id:continue
  npc=db.Get(db,'npcs',boss.id)
  loot=list(boss.loot.values()) if boss.loot else []
  bosses[int(boss.id)]={'name':npc.name if npc else 'NPC '+str(boss.id),'loot':loot}
  pairs+=len(loot)
 records[key]={'name':instance.name or str(key).replace('-',' ').title(),'area':instance.area,'bosses':bosses,'trash':list(instance.trash.values()) if instance.trash else []}
out=root/'RaynnaBestiary'
(out/'DungeonReference.lua').write_text('-- Generated by tools/build_bestiary_dungeons.py; NorgannonDB '+revision+'\n-- GPL-3.0; DungeonJournal by Exehn, compiled by Maro. See NOTICE-NorgannonDB.md.\nlocal _, A = ...\nA.DungeonReference = '+encode(records)+'\n',encoding='utf8')
(out/'NOTICE-NorgannonDB.md').write_bytes((src/'NOTICE.md').read_bytes())
print(len(records),'dungeons;',pairs,'boss/item relationships; revision',revision)
