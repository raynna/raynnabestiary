"""Build Forever crafting and NPC coordinates; run with PYTHONPATH=.test-deps.

--refresh fetches the licensed upstream client-data snapshot outside WoW.
Only factual data is exported, not third-party runtime code.
"""
import argparse, base64, hashlib, json, re, shutil, subprocess
from pathlib import Path
import cbor2
from lupa.lua51 import LuaRuntime
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'RaynnaCodex'
SOURCE = ROOT / 'tools/data-cache/DwarfExplorersBible'
parser = argparse.ArgumentParser()
parser.add_argument('--refresh', action='store_true')
parser.add_argument('--questie-toc', type=Path, default=Path('C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/QuestieDB/QuestieDB_Forever.toc'))
args = parser.parse_args()
if not SOURCE.exists():
    subprocess.run(['git','clone','--depth','1','https://github.com/masterred92/DwarfExplorersBible.git',str(SOURCE)], check=True)
elif args.refresh:
    subprocess.run(['git','-C',str(SOURCE),'fetch','origin','HEAD'],check=True)
    subprocess.run(['git','-C',str(SOURCE),'checkout','--detach','FETCH_HEAD'],check=True)
revision = subprocess.check_output(['git','-C',str(SOURCE),'rev-parse','HEAD'],text=True).strip()
runtime = LuaRuntime(unpack_returned_tuples=True)
namespace = runtime.table()
runtime.execute((SOURCE/'Data.lua').read_text(encoding='utf8'), 'Export', namespace)
data = namespace.Data
def lua(value):
    if isinstance(value, dict): return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
    if isinstance(value, list): return '{'+','.join(map(lua,value))+'}'
    return json.dumps(value,ensure_ascii=False)
records=[]
for _, encoded in data.recipes.items():
    product, minimum, maximum, profession, yellow, grey, spell, reagents = encoded.split(';')
    product,spell=int(product),int(spell)
    mats=[[int(a),int(b)] for a,b in re.findall(r'(\d+):(\d+)',reagents)]
    tools=list(data.tools[spell].values()) if data.tools[spell] else []
    records.append([spell,data.names[product] or f'Item {product}',data.professions[int(profession)],0,product,mats,[], 'Forever',int(yellow),int(grey),tools,int(minimum),int(maximum)])
records.sort(key=lambda r:(r[2],r[8],r[1],r[0]))
names=dict(data.names.items())
camp=[]
for _, encoded in data.camp.items():
    spell,reagent,action,place=encoded.split(';')
    item,count=map(int,reagent.split(':'))
    camp.append([int(spell),item,count,action,place])
text='-- Generated by tools/build_codex_forever.py; MIT client-derived factual data.\nlocal _, A = ...\n'
text+='A.RecipeRevision='+lua(revision)+'\nA.RecipeBuild='+lua(data.build)+'\nA.ItemNames='+lua(names)+'\nA.CampUses='+lua(camp)+'\nA.Recipes={\n'
text+=',\n'.join(map(lua,records))+'\n}\n'
(OUT/'ForeverRecipes.lua').write_text(text,encoding='utf8')
shutil.copy2(SOURCE/'LICENSE',OUT/'LICENSE-ForeverRecipes.txt')
source=args.questie_toc
blob=source.read_bytes()
metadata=dict(re.findall(r'^## ([^:]+): (.*)$',blob.decode('utf8'),re.M))
metadata={k:v.rstrip('\r') for k,v in metadata.items()}
def decode(key):
    value=metadata.get(key)
    if not value: return None
    if value.startswith('~'): value=''.join(metadata[f'{key}-{i}'] for i in range(1,int(value.strip('~'))+1))
    return cbor2.loads(base64.b64decode(value))
locations={}
for key in metadata:
    match=re.fullmatch(r'X-Npc-(\d+)-S',key)
    if not match: continue
    npc=int(match[1]); row=decode(key)
    spawns=(row.get(7) if isinstance(row,dict) else None) or decode(f'X-Npc-{npc}-7')
    if not isinstance(spawns,dict): continue
    clean={}
    for area, points in spawns.items():
        if not isinstance(area,int) or not isinstance(points,list): continue
        valid=[p[:2] for p in points if isinstance(p,list) and len(p)>=2 and all(isinstance(x,(int,float)) and 0<=x<=100 for x in p[:2])]
        if valid: clean[area]=valid
    if clean: locations[npc]=clean
(OUT/'Locations.lua').write_text('-- QuestieDB Forever coordinates; see LICENSE-QuestieDB.txt.\n-- Input SHA256: '+hashlib.sha256(blob).hexdigest()+'\nlocal _, A = ...\nA.NpcLocations='+lua(locations)+'\n',encoding='utf8')
for file in ['Portraits.lua','PortraitDisplays.lua']:
    if (ROOT/'RaynnaBestiary'/file).exists(): shutil.copy2(ROOT/'RaynnaBestiary'/file,OUT/file)
print(f'{len(records)} Forever recipes, {len(camp)} camp uses, {len(locations)} NPCs with coordinates; build {data.build}; {revision}')
