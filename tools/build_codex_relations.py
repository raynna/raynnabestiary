"""Export omitted Forever QuestieDB relationships. No player files are read."""
import argparse, base64, hashlib, json, re
from pathlib import Path
import cbor2
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--questie-toc',type=Path,default=Path('C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/QuestieDB/QuestieDB_Forever.toc'))
source=parser.parse_args().questie_toc
blob=source.read_bytes()
meta={k:v.rstrip('\r') for k,v in re.findall(r'^## ([^:]+): (.*)$',blob.decode('utf8'),re.M)}
def decode(key):
    value=meta.get(key)
    if value is None: return None
    if value.startswith('~'): value=''.join(meta[f'{key}-{i}'] for i in range(1,int(value.strip('~'))+1))
    return cbor2.loads(base64.b64decode(value))
def pos(row,index):
    if isinstance(row,dict): return row.get(index)
    if isinstance(row,list) and len(row)>=index: return row[index-1]
def field(entity,id,index):
    row=decode(f'X-{entity}-{id}-S')
    value=pos(row,index)
    return value if value is not None else decode(f'X-{entity}-{id}-{index}')
def lua(value):
    if value is None: return 'nil'
    if isinstance(value,bytes): value=value.decode('utf8')
    if isinstance(value,dict): return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
    if isinstance(value,list): return '{'+','.join(map(lua,value))+'}'
    return json.dumps(value,ensure_ascii=False)
def ids(entity):
    return sorted(int(m[1]) for key in meta if (m:=re.fullmatch('X-'+entity+r'-(\d+)-S',key)))
quests={}; supplied={}; requirements={}; objects={}; items={}
for id in ids('Quest'):
    quests[id]={name:field('Quest',id,index) for name,index in [('name',1),('startedBy',2),('requiredLevel',4),('questLevel',5),('sourceItemId',11),('requiredSourceItems',21)] if field('Quest',id,index) is not None}
    item=quests[id].get('sourceItemId')
    if isinstance(item,int) and item>0: supplied.setdefault(item,[]).append(id)
    for item in quests[id].get('requiredSourceItems',[]) or []:
        if isinstance(item,int) and item>0: requirements.setdefault(item,[]).append(id)
for id in ids('Object'):
    objects[id]={name:field('Object',id,index) for name,index in [('name',1),('spawns',4),('zoneID',5)] if field('Object',id,index) is not None}
for id in ids('Item'):
    values={name:field('Item',id,index) for name,index in [('objectDrops',3),('itemDrops',4),('teachesSpell',16)] if field('Item',id,index) is not None}
    if values: items[id]=values
out='-- Generated by tools/build_codex_relations.py; QuestieDB Forever; licensing in LICENSE-QuestieDB.txt.\n-- Input SHA256: '+hashlib.sha256(blob).hexdigest()+'\nlocal _, A = ...\n'
for name,value in [('QuestDetails',quests),('SuppliedItems',supplied),('RequiredItems',requirements),('Objects',objects),('ExtraItems',items)]: out+='A.'+name+'='+lua(value)+'\n'
(ROOT/'RaynnaCodex/Relations.lua').write_text(out,encoding='utf8')
assert 1136 in supplied.get(5838,[]), 'Frostmaw must supply Kodo Skin Scroll'
print(f'{len(supplied)} quest-supplied items; {len(requirements)} quest prerequisites; {len(items)} item relationships; {len(objects)} objects')
