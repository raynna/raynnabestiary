"""Export numeric Forever NPC/display facts; no artwork or third-party runtime copied."""
from pathlib import Path
import re,hashlib
root=Path(__file__).resolve().parents[1]
source=Path('C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/ForeverDungeonJournal/Data/Bosses.lua')
s=source.read_text();records={}
block=s.split('FDJ.STATIC_DISPLAY_IDS = {',1)[1].split('\n}',1)[0]
for npc,display in re.findall(r'^\s*\[(\d+)\]\s*=\s*(\d+)',block,re.M):
 if int(npc)>=200000:records[int(npc)]=int(display)
block=s.split('FDJ.TRASH_MOB_DISPLAY_IDS = {',1)[1].split('\n}',1)[0]
for display,comment in re.findall(r'^\s*\["[^"]+"\]\s*=\s*(\d+),\s*-- npc ([^\n]+)',block,re.M):
 for npc in re.findall(r'\b\d{6}\b',comment):records[int(npc)]=int(display)
text='-- Generated by tools/build_forever_portraits.py. Numeric display mappings only.\n-- Source: DungeonJournal by Exehn 2.1.0; Bosses.lua SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\nlocal _, A = ...\nlocal displays = {\n'+''.join(f'    [{k}] = {v},\n' for k,v in sorted(records.items()))+'}\nfor npc, display in pairs(displays) do A.PortraitDisplays[npc] = display end\n'
(root/'RaynnaBestiary/ForeverPortraits.lua').write_text(text)
print('Exported',len(records),'Forever NPC/display mappings')
